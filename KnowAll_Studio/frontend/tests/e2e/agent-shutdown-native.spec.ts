import { test, expect } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
const out = resolve('../docs/open-source-integration/native-agent-shutdown-2026-10-11/native-browser')
test.beforeEach(async ({ page }) => {
  test.skip(!process.env.AGENT_NATIVE_CONTROL, 'Run via temporary SQL/native provider harness')
  await page.addInitScript(token => { localStorage.setItem('knowall_token', token); localStorage.setItem('knowall_user', JSON.stringify({ id: 'alice', username: 'alice', email: 'alice@test.invalid' })) }, process.env.AGENT_NATIVE_TOKEN!)
  await page.route('**/api/**', async route => {
    const path = new URL(route.request().url()).pathname
    if (path.startsWith('/api/v1/agent/') || path.startsWith('/api/v1/chat/')) await route.fallback()
    else await route.fulfill({ json: [] })
  })
  await page.routeWebSocket(/\/ws\//, () => {}); await mkdir(out, { recursive: true })
})
async function begin(page: import('@playwright/test').Page, question: string) {
  await page.goto('/chat'); await page.getByRole('switch', { name: '只读资料 Agent' }).click()
  await page.getByRole('switch', { name: '离开页面后继续' }).click()
  await page.getByRole('textbox', { name: '输入学习问题' }).fill(question)
  await page.getByRole('button', { name: /发送$/ }).click()
  await expect(page.locator('.chat-agent-live')).toContainText('请求模型判断下一步')
  await page.getByText('执行记录', { exact: true }).click()
  await expect(page.getByText('资料检索完成', { exact: true })).toBeVisible()
  return page.evaluate(() => JSON.parse(localStorage.getItem('knowall_agent_observed_run:alice')!).run_id as string)
}
test('actual background continues after reload, is discoverable without pointer, and restores actual conversation', async ({ page, request }) => {
  let starts = 0; let stops = 0
  page.on('request', req => { if (req.method() === 'POST' && new URL(req.url()).pathname === '/api/v1/agent/runs') starts++; if (req.method() === 'POST' && new URL(req.url()).pathname.endsWith('/cancel')) stops++ })
  const runId = await begin(page, '后台实时验证细胞呼吸')
  await page.reload(); await expect(page.getByRole('button', { name: '继续查看进度' })).toBeVisible()
  await page.evaluate(() => localStorage.removeItem('knowall_agent_observed_run:alice'))
  await page.reload(); await expect(page.getByRole('region', { name: '上次资料任务' })).toHaveCount(0)
  await page.getByRole('button', { name: '查看任务记录' }).focus(); await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog').getByText('运行中', { exact: true })).toBeVisible()
  const live = await (await request.get(process.env.AGENT_NATIVE_CONTROL! + '/state')).json()
  expect(live.message_count).toBe(0); expect(live.runs.find((r: { id: string }) => r.id === runId).status).toBe('running')
  for (const width of [1440, 375]) for (const theme of ['light', 'dark']) {
    await page.keyboard.press('Escape'); await page.setViewportSize({ width, height: width === 375 ? 812 : 1000 })
    if (await page.locator('html').getAttribute('data-theme') !== theme) await page.getByRole('button', { name: theme === 'dark' ? '切换到深色模式' : '切换到浅色模式' }).click()
    await page.getByRole('button', { name: '查看任务记录' }).click()
    await expect(page.getByRole('dialog').getByText('运行中', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await page.screenshot({ path: resolve(out, `actual-list-${width}-${theme}.png`), fullPage: true, animations: 'disabled' })
  }
  await page.getByRole('dialog').getByRole('button', { name: '核对运行状态' }).click()
  await page.getByRole('button', { name: '继续查看进度' }).click()
  await expect(page.locator('.chat-agent-live')).toContainText('请求模型判断下一步')
  await request.post(process.env.AGENT_NATIVE_CONTROL! + '/release')
  await expect(page.locator('.chat-markdown')).toContainText('细胞呼吸消耗氧气 [S1]')
  await page.setViewportSize({ width: 1440, height: 1000 }); await page.reload()
  await page.getByRole('button', { name: /后台实时验证细胞呼吸.*答疑助教/ }).click()
  await expect(page.locator('.chat-markdown')).toContainText('细胞呼吸消耗氧气 [S1]')
  expect(starts).toBe(1); expect(stops).toBe(0)
  await writeFile(resolve(out, 'background-after-reload.json'), JSON.stringify({ scope: 'actual production browser/Vite proxy/main/JWT/temp SQL/native HTTP adapter; only provider explicitly simulated; no Agent/Chat mocks', run_id: runId, starts, stops, live }, null, 2))
})
test('actual explicit background stop persists request and only then real cancelled state', async ({ page, request }) => {
  await request.post(process.env.AGENT_NATIVE_CONTROL! + '/reset')
  const runId = await begin(page, '后台停止验证细胞呼吸')
  await page.getByRole('button', { name: '停止后台任务' }).focus(); await page.keyboard.press('Enter')
  await expect(page.locator('.chat-message-content .ant-alert')).toContainText('资料任务已取消')
  await expect(page.getByRole('textbox', { name: '输入学习问题' })).toBeFocused()
  const after = await (await request.get(process.env.AGENT_NATIVE_CONTROL! + '/state')).json()
  const cancelled = after.runs.find((r: { id: string }) => r.id === runId)
  expect(cancelled.status).toBe('cancelled'); expect(cancelled.steps.at(-1).type).toBe('run_cancelled')
  expect(after.controls.find((c: { run_id: string }) => c.run_id === runId).cancel_requested).toBe(true)
  expect(after.message_count).toBe(2)
  await request.post(process.env.AGENT_NATIVE_CONTROL! + '/release')
  await page.reload(); await expect(page.getByText('上次资料任务已取消', { exact: true })).toBeVisible()
  await page.getByText('查看已保存步骤', { exact: true }).click()
  const inspection = page.locator('.chat-agent-inspection')
  await expect(inspection.getByText('任务已取消', { exact: true })).toBeVisible()
  await expect(inspection.locator('.chat-agent-steps')).toContainText('simulated-native')
  await expect(inspection.locator('.chat-agent-inspection-read time')).toHaveCount(1)
  await expect(inspection.locator('.chat-agent-live')).toHaveCount(0)
  for (const width of [1440, 375]) for (const theme of ['light', 'dark']) {
    await page.setViewportSize({ width, height: width === 375 ? 812 : 1000 })
    if (await page.locator('html').getAttribute('data-theme') !== theme) await page.getByRole('button', { name: theme === 'dark' ? '切换到深色模式' : '切换到浅色模式' }).click()
    await inspection.locator('.chat-agent-steps > p').scrollIntoViewIfNeeded()
    await page.screenshot({ path: resolve(out, `actual-inspection-${width}-${theme}.png`), fullPage: true, animations: 'disabled' })
  }
  await page.getByRole('button', { name: '查看任务记录' }).click()
  await expect(page.getByRole('dialog').getByText('已取消', { exact: true })).toBeVisible()
  await expect(page.getByRole('dialog').getByText('已完成', { exact: true })).toBeVisible()
  await page.screenshot({ path: resolve(out, 'actual-complete-and-cancelled.png'), fullPage: true, animations: 'disabled' })
  await writeFile(resolve(out, 'actual-cancel.json'), JSON.stringify({ run_id: runId, after, paid_calls: 0 }, null, 2))
})
