/** Real JWT / SQL / backend / native HTTP adapter. Provider is explicitly local simulation. */
import { test, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import path from 'node:path'

test('saved configuration drives an uploaded document into real persisted cards and map', async ({ page }) => {
  test.skip(!process.env.MODEL_CONFIG_BACKEND, 'Run through the isolated backend pytest harness')
  const out = path.resolve('../docs/model-configuration-2026-10-20')
  mkdirSync(out, { recursive: true })
  await page.addInitScript(token => {
    localStorage.setItem('knowall_token', token!)
    localStorage.setItem('knowall_user', JSON.stringify({ id: 'alice', username: 'alice', email: 'alice@test.invalid' }))
  }, process.env.MODEL_CONFIG_TOKEN)
  await page.routeWebSocket(/\/ws\//, () => {})
  await page.route('**/api/**', async route => {
    const url = new URL(route.request().url())
    if (/^\/api\/v1\/(ai\/|documents\/|learning\/|agent\/models)/.test(url.pathname)) {
      const response = await route.fetch({ url: process.env.MODEL_CONFIG_BACKEND + url.pathname + url.search })
      return route.fulfill({ response })
    }
    return route.fulfill({ json: [] })
  })
  await page.goto('/settings', { waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: '添加连接', exact: true }).click()
  await page.getByRole('textbox', { name: '连接名称', exact: true }).fill('本机验证网关')
  await page.getByRole('textbox', { name: 'API 基础地址', exact: true }).fill(process.env.MODEL_CONFIG_PROVIDER!)
  await page.getByLabel('API Key', { exact: true }).fill('synthetic-private-key')
  await page.getByRole('button', { name: '保存连接', exact: true }).click()
  let card = page.getByRole('article', { name: '模型连接 本机验证网关' })
  await expect(card).toContainText('已保存（加密）')
  await card.getByRole('button', { name: '获取模型', exact: true }).click()
  await expect(card).toContainText('服务商可用模型：1 个')
  await card.getByRole('button', { name: /编\s*辑/ }).click()
  await expect(page.getByLabel('API Key', { exact: true })).toHaveValue('')
  await page.getByRole('combobox', { name: '模型 ID', exact: true }).fill('vendor/brand-new')
  await page.getByRole('button', { name: '保存连接', exact: true }).click()
  await expect(card).toContainText('vendor/brand-new')
  await card.getByRole('button', { name: '测试生成', exact: true }).click()
  await expect(card).toContainText('连接和生成测试通过')
  await card.getByRole('button', { name: '设为默认', exact: true }).click()
  await expect(page.getByLabel('当前默认模型')).toContainText('本机验证网关 / vendor/brand-new')
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByLabel('当前默认模型')).toContainText('本机验证网关 / vendor/brand-new')
  await page.screenshot({ path: path.join(out, 'settings-light.png'), fullPage: true })
  await page.getByRole('button', { name: '切换到深色模式' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(card).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: path.join(out, 'settings-dark-mobile.png'), fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/materials/' + process.env.MODEL_CONFIG_DOCUMENT, { waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: '整理学习内容', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '学习生成模型' })).toHaveValue(/^connection-[^/]+\/vendor\/brand-new$/)
  await page.getByRole('spinbutton', { name: '生成习题数量' }).fill('0')
  await page.getByRole('spinbutton', { name: '生成知识卡数量' }).fill('1')
  await page.getByRole('button', { name: '生成学习包', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('tab', { name: '知识卡', exact: true }).click()
  await expect(page.getByText('细胞膜的作用是什么？', { exact: true })).toBeVisible()
  await page.screenshot({ path: path.join(out, 'generated-card.png'), fullPage: true })
  await page.getByRole('tab', { name: '导图', exact: true }).click()
  await expect(page.getByRole('link', { name: '打开完整思维导图' })).toBeVisible()
  await page.screenshot({ path: path.join(out, 'generated-map.png'), fullPage: true })
})
