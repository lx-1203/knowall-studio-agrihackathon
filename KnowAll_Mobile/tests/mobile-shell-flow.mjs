import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { mockShell } from './mobile-shell-fixture.mjs'
const require = createRequire(new URL('../../KnowAll_Studio/frontend/package.json', import.meta.url))
const { chromium, expect } = require('@playwright/test')
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const theme = process.env.MOBILE_UI_THEME || 'light', width = Number(process.env.MOBILE_UI_WIDTH || 390)
const base = process.env.MOBILE_UI_URL || 'http://localhost:8096'
const page = await browser.newPage({ viewport: { width, height: 844 }, colorScheme: theme })
const state = await mockShell(page), errors = []
page.on('pageerror', e => errors.push(e.message))
const cases = process.env.MOBILE_UI_CASE || 'study'
const button = name => page.getByRole('button', { name, exact: true })
const text = name => page.getByText(name, { exact: true })
const shot = async name => {
  await page.mouse.move(0, 0)
  await page.waitForTimeout(400) // Let Paper's press ripple and dialog transitions settle.
  await page.screenshot({ path: fileURLToPath(new URL('../docs/patrol/' + (process.env.MOBILE_UI_EVIDENCE_DIR || 'ui02-01a12efd') + '/after-' + name + '-' + theme + '-' + width + '.png', import.meta.url)), fullPage: true })
}
const calls = (path, method) => state.calls.filter(c => c.path === path && c.method === method)
const checkWidth = async () => {
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  expect(overflow).toBeLessThanOrEqual(1)
  const color = await text(cases === 'study' ? '学习计划' : cases === 'profile' ? '我的' : cases === 'review' ? '复习' : '添加资料').first().evaluate(el => getComputedStyle(el).color)
  expect(color).toBe(theme === 'dark' ? 'rgb(229, 232, 223)' : 'rgb(36, 42, 38)')
}
try {
  if (cases === 'study') {
    state.longSchedule = true
    await page.goto(base + '/study')
    await text('期末复习 · 细胞生物学').click()
    await expect(text('复习第一章')).toBeVisible({ timeout: 15000 })
    await checkWidth()
    await shot('study')
    await button('展开全部日程').click()
    await expect(page.getByText('19:00 · 最后一章核对')).toBeVisible()
    await expect(page.getByText(/第二周回顾任务/)).toBeVisible()
    await page.getByRole('checkbox', { name: '复习第一章' }).click()
    await expect.poll(() => state.goalDone).toBe(true)
    expect(calls('/study/goals/goal-a/toggle', 'PUT')).toHaveLength(1)
    state.faults['/study/goals/goal-a/toggle'] = true
    await page.getByRole('checkbox', { name: '复习第一章' }).click()
    await expect(page.getByText(/目标状态未确认/)).toBeVisible()
    expect(calls('/study/goals/goal-a/toggle', 'PUT')).toHaveLength(2)
    expect(state.goalDone).toBe(true)
    delete state.faults['/study/goals/goal-a/toggle']
    await button('重试').click()
    await expect(page.getByRole('checkbox', { name: '复习第一章' })).toHaveAttribute('aria-checked', 'true')
    state.lostToggle = true
    await page.getByRole('checkbox', { name: '复习第一章' }).click()
    await expect(page.getByText(/目标状态未确认/)).toBeVisible()
    expect(state.goalDone).toBe(false)
    expect(calls('/study/goals/goal-a/toggle', 'PUT')).toHaveLength(3)
    await button('重试').click()
    await expect(page.getByRole('checkbox', { name: '复习第一章' })).toHaveAttribute('aria-checked', 'false')
    await expect(text('已完成 0%')).toBeVisible()
    await button('添加目标').click()
    await page.getByLabel('目标内容', { exact: true }).fill('整理错题')
    await button('添加').click()
    await expect(text('整理错题')).toBeVisible()
    await button('删除计划').click()
    await button('取消').click()
    expect(calls('/study/plans/plan-a', 'DELETE')).toHaveLength(0)
    await button('新建').click()
    await button('创建').click()
    await expect(text('请给计划取一个名字。')).toBeVisible()
    await page.getByLabel('计划名称', { exact: true }).fill('下周复习安排')
    await page.getByLabel('计划说明（选填）', { exact: true }).fill('每天一小步')
    await page.getByLabel('第一个目标（选填）', { exact: true }).fill('复习第三章')
    state.faults['/study/plans'] = true
    await button('创建').click()
    await expect(text('隔离测试故障')).toBeVisible()
    await expect(page.getByLabel('计划名称', { exact: true })).toHaveValue('下周复习安排')
    expect(calls('/study/plans', 'POST')).toHaveLength(1)
    delete state.faults['/study/plans']
    await button('创建').click()
    await expect(text('下周复习安排')).toBeVisible()
    expect(JSON.parse(calls('/study/plans', 'POST').at(-1).body).goals).toEqual([{ title: '复习第三章' }])
    await text('下周复习安排').click()
    await expect(text('复习第一章')).toBeVisible()
    await button('删除计划').click()
    await button('确认删除').click()
    await expect(text('下周复习安排')).toHaveCount(0)
    expect(calls('/study/plans/plan-new', 'DELETE')).toHaveLength(1)
  }
  if (cases === 'upload') {
    await page.goto(base + '/upload')
    await expect(text('添加资料')).toBeVisible()
    await checkWidth()
    await shot('upload')
    await button('上传资料').click()
    await expect(text('先选择一个文件。')).toBeVisible()
    const chooser = page.waitForEvent('filechooser')
    await button('选择文件').click()
    const bytes = Buffer.from('第一章 细胞\n隔离预览真实文件字节-01a12efd')
    await (await chooser).setFiles({ name: '期末复习讲义.md', mimeType: 'text/markdown', buffer: bytes })
    await expect(page.getByTestId('picked-file')).toContainText('期末复习讲义.md')
    await page.getByLabel('科目（可留空）', { exact: true }).fill('生物')
    await text('题库资料').click()
    state.faults['/documents/shell-doc/organization'] = true
    await button('上传资料').click()
    await expect(text('资料已保存 · 分类待保存')).toBeVisible()
    await shot('upload-classification-failed')
    const upload = calls('/documents/upload', 'POST')
    expect(upload).toHaveLength(1)
    expect(upload[0].body).toContain(bytes.toString())
    expect(upload[0].body).toContain('filename="期末复习讲义.md"')
    expect(upload[0].body).not.toContain('[object Object]')
    delete state.faults['/documents/shell-doc/organization']
    await button('重试保存分类').click()
    await expect(text('资料和分类已保存')).toBeVisible()
    expect(calls('/documents/upload', 'POST')).toHaveLength(1)
    expect(JSON.parse(calls('/documents/shell-doc/organization', 'PATCH').at(-1).body)).toEqual({ subject: '生物', material_kind: 'question_bank' })
    await button('打开资料开始学习').click()
    await expect(page).toHaveURL(/material.*shell-doc/)
    await page.goto(base + '/upload')
    await text('网页链接').first().click()
    await page.getByLabel('网页链接', { exact: true }).fill('javascript:alert(1)')
    await button('导入网页').click()
    await expect(text('请输入完整的 http:// 或 https:// 网页链接。')).toBeVisible()
    expect(calls('/documents/import-url', 'POST')).toHaveLength(0)
    await page.getByLabel('网页链接', { exact: true }).fill('https://example.test/article')
    state.faults['/documents/import-url'] = true
    await button('导入网页').click()
    await expect(text('隔离测试故障')).toBeVisible()
    expect(calls('/documents/import-url', 'POST')).toHaveLength(1)
    await expect(page.getByLabel('网页链接', { exact: true })).toHaveValue('https://example.test/article')
    delete state.faults['/documents/import-url']
    await button('导入网页').click()
    await expect(text('资料和分类已保存')).toBeVisible()
  }
  if (cases === 'review') {
    await page.goto(base + '/review')
    await expect(text('细胞膜的主要作用是什么？')).toBeVisible()
    await checkWidth(); await shot('review')
    await button('查看答案').click()
    await expect(text('调节物质交换，接收外界信号。')).toBeVisible()
    await shot('review-answer')
    state.faults['/flashcards/review'] = true
    await button('记住了').click()
    await expect(text('隔离测试故障')).toBeVisible()
    expect(calls('/flashcards/review', 'POST')).toHaveLength(1)
    expect(state.cardDone).toBe(false)
    await expect(text('调节物质交换，接收外界信号。')).toBeVisible()
    delete state.faults['/flashcards/review']
    state.delays['/flashcards/review'] = 300
    await button('记住了').dblclick({ delay: 30 })
    await expect(text('本次已完成 1 张')).toBeVisible()
    expect(calls('/flashcards/review', 'POST')).toHaveLength(2)
    expect(JSON.parse(calls('/flashcards/review', 'POST').at(-1).body)).toEqual({ card_id: 'card-a', rating: 3 })
    await expect(text('0 张待复习')).toBeVisible()
    await shot('review-done')
    await text('全部题库').click(); await expect(page).toHaveURL(/quiz/)
  }
  if (cases === 'profile') {
    state.feedMany = true
    await page.goto(base + '/profile')
    await expect(text('小林')).toBeVisible()
    await checkWidth(); await shot('profile')
    await text('通知 · 6 未读').click()
    await button('加载更多通知').click()
    await expect(text('第六条通知')).toBeVisible()
    await button('全部标为已读').click()
    await expect(text('通知 · 0 未读')).toBeVisible()
    await text('最近活动').click()
    await button('加载更多活动').click()
    await expect(text('第六条活动')).toBeVisible()
    await text('修改昵称').click()
    await page.getByLabel('昵称', { exact: true }).fill('小林同学')
    state.faults['/user/profile'] = true
    await button('保存').click()
    await expect(text('隔离测试故障')).toBeVisible()
    expect(calls('/user/profile', 'PUT')).toHaveLength(1)
    await expect(page.getByLabel('昵称', { exact: true })).toHaveValue('小林同学')
    delete state.faults['/user/profile']
    await button('保存').click()
    await expect(text('小林同学')).toBeVisible()
    state.faults['/user/profile'] = true
    await page.getByRole('tab', { name: '计划', exact: true }).click()
    await page.getByRole('tab', { name: '我的', exact: true }).click()
    await expect(text('账户资料暂时无法读取。')).toBeVisible({ timeout: 12000 })
    await expect(text('小林同学')).toBeVisible()
    delete state.faults['/user/profile']
    await button('重试').click()
    await expect(text('账户资料暂时无法读取。')).toHaveCount(0)
    await text('修改密码').click()
    await button('保存').click()
    await expect(text('请填写旧密码、新密码和确认密码。')).toBeVisible()
    await page.getByLabel('旧密码', { exact: true }).fill('old-preview-123')
    await page.getByLabel('新密码', { exact: true }).fill('new-preview-456')
    await page.getByLabel('确认新密码', { exact: true }).fill('new-preview-789')
    await button('保存').click()
    await expect(text('两次新密码不一致，请核对。')).toBeVisible()
    await page.getByLabel('确认新密码', { exact: true }).fill('new-preview-456')
    state.faults['/user/password'] = true
    await button('保存').click()
    await expect(text('隔离测试故障')).toBeVisible()
    expect(calls('/user/password', 'PUT')).toHaveLength(1)
    delete state.faults['/user/password']
    await button('保存').click()
    await expect(text('密码已修改')).toBeVisible()
    await page.getByRole('switch', { name: '深色外观' }).click()
    await expect(text(theme === 'dark' ? '已关闭' : '已开启')).toBeVisible()
    await page.getByRole('switch', { name: '深色外观' }).click()
    await button('退出登录').click(); await button('取消').click()
    await expect(text('小林同学')).toBeVisible()
    await button('退出登录').click(); await button('确认退出').click()
    await expect(page).toHaveURL(/login/)
    expect(await page.evaluate(() => localStorage.getItem('knowall_token'))).toBeNull()
  }
  expect(state.calls.filter(c => /generate|recommend/.test(c.path) && c.method !== 'GET')).toHaveLength(0)
  expect(errors).toEqual([])
  console.log('PASS ' + cases + '/' + theme + '/' + width + ' requests=' + state.calls.length)
} finally { await browser.close() }
