// Rebuild offline CSS from the pinned KaTeX package. No CDN or font requests at runtime.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
const require = createRequire(import.meta.url)
const folder = path.dirname(require.resolve('katex/package.json'))
let css = await readFile(path.join(folder, 'dist/katex.min.css'), 'utf8')
const fonts = new Set()
css = css.replace(/src:([^;}]+)/g, (_, source) => {
  const name = /url\((fonts\/[^)]+\.woff2)\)/.exec(source)?.[1]
  if (!name) throw new Error('Missing WOFF2 font in pinned KaTeX CSS')
  fonts.add(name)
  return `src:__FONT_${name}__`
})
for (const name of fonts) {
  const bytes = await readFile(path.join(folder, 'dist', name))
  css = css.replaceAll(`__FONT_${name}__`, `url(data:font/woff2;base64,${bytes.toString('base64')}) format("woff2")`)
}
const output = new URL('../src/generated/katexOfflineCss.js', import.meta.url)
await mkdir(new URL('../src/generated/', import.meta.url), { recursive: true })
await writeFile(output, '// Generated by scripts/generate-katex-assets.mjs from pinned KaTeX; preserve its MIT license.\nexport const katexOfflineCss = ' + JSON.stringify(css) + '\n')
await writeFile(new URL('../src/generated/katexOfflineCss.d.ts', import.meta.url), 'export declare const katexOfflineCss: string\n')
await mkdir(new URL('../docs/third-party/', import.meta.url), { recursive: true })
await writeFile(new URL('../docs/third-party/katex-LICENSE', import.meta.url), await readFile(path.join(folder, 'LICENSE')))
console.log(`Embedded ${fonts.size} offline WOFF2 fonts; ${css.length} CSS characters.`)
